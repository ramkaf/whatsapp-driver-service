CREATE TABLE `wasessionlogs` (
    `id` VARCHAR(30) NOT NULL,
    `session_id` VARCHAR(191) NULL,
    `level` ENUM('INFO', 'WARN', 'ERROR', 'EXCEPTION', 'RETRY') NOT NULL,
    `event` VARCHAR(100) NOT NULL,
    `context` VARCHAR(100) NOT NULL,
    `message` TEXT NOT NULL,
    `metadata` JSON NULL,
    `error_name` VARCHAR(191) NULL,
    `error_message` TEXT NULL,
    `error_stack` TEXT NULL,
    `status` ENUM('DISCONNECTED', 'CONNECTING', 'AWAITING_PAIRING', 'CONNECTED', 'LOGGED_OUT', 'RECONNECTING', 'FAILED', 'EXPIRED', 'AUTHENTICATING') NULL,
    `socket_connected` BOOLEAN NULL,
    `generation` INTEGER NULL,
    `retry_count` INTEGER NULL,
    `next_retry_at` DATETIME(3) NULL,
    `connected_at` DATETIME(3) NULL,
    `last_disconnected_at` DATETIME(3) NULL,
    `expires_at` DATETIME(3) NULL,
    `qr_expires_at` DATETIME(3) NULL,
    `code_expires_at` DATETIME(3) NULL,
    `state_since` DATETIME(3) NULL,
    `disconnect_code` INTEGER NULL,
    `reason` VARCHAR(100) NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    INDEX `wasessionlogs_session_id_created_at_idx`(`session_id`, `created_at`),
    INDEX `wasessionlogs_level_created_at_idx`(`level`, `created_at`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
